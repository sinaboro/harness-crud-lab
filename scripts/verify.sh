#!/bin/sh
# ============================================================
# verify.sh - 검증 스크립트 (하네스의 "검증" 담당)
#
# 사람이든 AI 든, 코드를 고친 뒤에는 반드시 이 스크립트를 통과해야 한다.
# 통과하지 못하면 Git 에 저장(commit)할 수 없다. (.githooks/pre-commit 이 막는다)
#
# 실행 (dev 컨테이너 안에서):  sh scripts/verify.sh
# ============================================================

# 명령 하나라도 실패하면 그 자리에서 멈춘다.
set -e

echo "[1/2] 코드 검사 (ruff) ----------------------------"
# 오타, 안 쓰는 import, 정의되지 않은 이름 같은 실수를 찾는다.
ruff check app tests scripts

echo "[2/2] 자동 테스트 (pytest) ------------------------"
# tests 폴더의 테스트를 모두 실행한다. 하나라도 실패하면 여기서 멈춘다.
pytest -q

echo "----------------------------------------------------"
echo "검증 통과: 이제 저장(commit)해도 됩니다."
